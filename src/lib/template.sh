#!/usr/bin/env bash
# template.sh — render schema-derived text: the commented system config, the legacy
# hyprlang binds and the human-readable config view. The committed files must equal this
# output (a test fails otherwise), so defaults and help live in settings.schema only.

# zoomctl_group_title — presentation title of a schema group id.
# Args:    $1 group id (zoom|tracking|filter|shortcuts|advanced|...)
# Returns: 0 always; stdout: title (the id itself for unknown groups)
# Globals: none
zoomctl_group_title() {
  # Titles are presentation only; the schema owns the group membership.
  case "$1" in
    zoom) printf 'Zoom\n' ;;
    tracking) printf 'Pointer tracking\n' ;;
    # Group ids come from the schema; the titles are presentation only.
    filter) printf 'Colour filter\n' ;;
    shortcuts) printf 'Shortcuts\n' ;;
    advanced) printf 'Advanced\n' ;;
    # An unknown group is shown by its id.
    *) printf '%s\n' "$1" ;;
  esac
}

# zoomctl_template_groups — list the group ids in order of first appearance.
# Args:    none
# Returns: 0 always; stdout: one group id per line
# Globals: reads ZOOMCTL_SCHEMA_KEYS, ZOOMCTL_SCHEMA_GROUP
zoomctl_template_groups() {
  local key
  local -A seen_groups=()
  # First appearance order mirrors the page order of the settings UI.
  for key in "${ZOOMCTL_SCHEMA_KEYS[@]}"; do
    [ -n "${seen_groups[${ZOOMCTL_SCHEMA_GROUP[$key]}]+set}" ] && continue
    seen_groups[${ZOOMCTL_SCHEMA_GROUP[$key]}]=1
    # Print each group id once, in order of first appearance.
    printf '%s\n' "${ZOOMCTL_SCHEMA_GROUP[$key]}"
  done
}

# zoomctl_template_comment_block — print text as wrapped "# " comment lines.
# Args:    $1 text
# Returns: 0 always; stdout: comment lines of at most 76 characters
# Globals: none
zoomctl_template_comment_block() {
  # fold breaks at blanks; sed removes trailing blanks and adds the comment marker.
  printf '%s\n' "$1" | fold -s -w 74 | sed -e 's/[[:space:]]*$//' -e 's/^/# /'
}

# zoomctl_template_key — render one commented setting with label, help and default.
# Args:    $1 canonical key
# Returns: 0 always; stdout: a block of comment lines plus the commented assignment
# Globals: reads the ZOOMCTL_SCHEMA_* tables
zoomctl_template_key() {
  local key="$1"
  # Label as headline, then the schema help, then the accepted values.
  printf '# %s\n' "${ZOOMCTL_SCHEMA_LABEL[$key]}"
  zoomctl_template_comment_block "${ZOOMCTL_SCHEMA_HELP[$key]}"
  zoomctl_template_comment_block "Accepts: $(zoomctl_schema_allowed_text "$key")"
  # The assignment stays commented out so the built-in default keeps applying.
  printf '#%s=%s\n\n' "$key" "${ZOOMCTL_SCHEMA_DEFAULT[$key]}"
}

# zoomctl_template_render — render the whole commented system config (config/defaults.conf).
# Args:    none (schema must be loaded)
# Returns: 0 always; stdout: the file content
# Globals: reads the ZOOMCTL_SCHEMA_* tables
zoomctl_template_render() {
  local group_id key
  # A fixed header explains the layering and where user overrides belong.
  cat <<'EOF'
# hyprland-zoom system defaults, installed as /etc/zoomctl.conf.
# Generated by `zoomctl config --template` from settings.schema; do not edit.
#
# Every setting is commented out and shows its built-in default. Uncomment a
# line to change it for all users. Personal overrides belong in
# ~/.config/zoomctl/zoom.conf, best written with `zoomctl set KEY VALUE` or
# the settings window (`zoomctl ui`).
# Effective value: built-in default <- this file <- the user file.

EOF
  # One section per schema group, keys in schema order.
  while read -r group_id; do
    printf '# ---- %s ----\n\n' "$(zoomctl_group_title "$group_id")"
    for key in "${ZOOMCTL_SCHEMA_KEYS[@]}"; do
      # An explicit if keeps a non-matching last key from failing the whole function.
      if [ "${ZOOMCTL_SCHEMA_GROUP[$key]}" = "$group_id" ]; then zoomctl_template_key "$key"; fi
    done
  done < <(zoomctl_template_groups)
}

# zoomctl_hyprlang_modifiers — convert "SUPER + ALT" to the hyprlang form "SUPER ALT".
# Args:    $1 canonical modifier list
# Returns: 0 always; stdout: space separated modifiers
# Globals: none
zoomctl_hyprlang_modifiers() {
  # hyprlang separates modifiers with blanks, the schema uses " + ".
  printf '%s\n' "${1// + / }"
}

# zoomctl_legacy_bind_line — render one hyprlang bind line.
# Args:    $1 bind keyword (bind|binde); $2 modifiers; $3 key; $4 zoomctl arguments
# Returns: 0 always; stdout: the line
# Globals: none
zoomctl_legacy_bind_line() {
  # The exec dispatcher runs the CLI, which does the flock-serialised legacy math.
  printf '%s = %s, %s, exec, zoomctl %s\n' "$1" "$2" "$3" "$4"
}

# zoomctl_legacy_key_binds — render the key binds that exist for non-empty schema keys.
# Args:    $1 hyprlang modifiers
# Returns: 0 always; stdout: bind lines
# Globals: reads ZOOMCTL_SCHEMA_DEFAULT
zoomctl_legacy_key_binds() {
  local modifiers="$1"
  local spec key_setting bind_keyword action
  # Zoom keys repeat while held (binde); toggle and settings fire once.
  for spec in BIND_KEY_IN:binde:in BIND_KEY_OUT:binde:out \
    BIND_KEY_TOGGLE:bind:toggle BIND_KEY_SETTINGS:bind:ui; do
    IFS=: read -r key_setting bind_keyword action <<< "$spec"
    # An empty default key means the bind is disabled.
    [ -n "${ZOOMCTL_SCHEMA_DEFAULT[$key_setting]}" ] || continue
    zoomctl_legacy_bind_line "$bind_keyword" "$modifiers" \
      "${ZOOMCTL_SCHEMA_DEFAULT[$key_setting]}" "$action"
  done
}

# zoomctl_legacy_bindings_render — render config/hyprland-bindings.conf from the schema defaults.
# Args:    none (schema must be loaded)
# Returns: 0 always; stdout: the file content
# Globals: reads ZOOMCTL_SCHEMA_DEFAULT
zoomctl_legacy_bindings_render() {
  local modifiers
  modifiers="$(zoomctl_hyprlang_modifiers "${ZOOMCTL_SCHEMA_DEFAULT[BIND_MODIFIERS]}")"
  # The header is fixed text; only the scroll delay comes from the schema.
  cat <<EOF
# hyprland-zoom binds for the legacy hyprlang config (Hyprland without hyprland.lua).
# Generated by \`zoomctl config --legacy-bindings\` from settings.schema; do not edit.
# \`zoomctl setup\` adds a \`source =\` line for this file to hyprland.conf.
# The Lua config loads hyprland-zoom.lua instead; this file is not used there.

# Let every scroll notch through to the binds instead of dropping fast ones.
binds {
    scroll_event_delay = ${ZOOMCTL_SCHEMA_DEFAULT[SCROLL_EVENT_DELAY_MS]}
}

EOF
  # Wheel and middle click, then the repeating and one-shot keys.
  zoomctl_legacy_bind_line bind "$modifiers" mouse_up 'in'
  zoomctl_legacy_bind_line bind "$modifiers" mouse_down 'out'
  zoomctl_legacy_bind_line bind "$modifiers" mouse:274 'toggle'
  # The key binds follow the BIND_KEY_* defaults of the schema.
  zoomctl_legacy_key_binds "$modifiers"
  # Colour filters need the Lua engine, so there is deliberately no filter bind here.
  printf '\n# Colour filters are not available on the legacy config.\n'
}

# zoomctl_config_render_human — print the effective configuration grouped, with the origin layer.
# Args:    none (config must be loaded)
# Returns: 0 always; stdout: readable table
# Globals: reads ZOOMCTL_VALUE, ZOOMCTL_SOURCE and the schema tables
zoomctl_config_render_human() {
  local group_id key
  printf 'hyprland-zoom configuration\n  user file:   %s\n  system file: %s\n' \
    "$(zoomctl_user_config_file)" "$(zoomctl_system_config_file)"
  # Group by schema page; mark where each value comes from.
  while read -r group_id; do
    printf '\n%s\n' "$(zoomctl_group_title "$group_id")"
    for key in "${ZOOMCTL_SCHEMA_KEYS[@]}"; do
      # Only the keys of the current group are listed.
      [ "${ZOOMCTL_SCHEMA_GROUP[$key]}" = "$group_id" ] || continue
      printf '  %-24s %-14s (%s)\n' "$key" "${ZOOMCTL_VALUE[$key]}" "${ZOOMCTL_SOURCE[$key]}"
    done
  done < <(zoomctl_template_groups)
}
