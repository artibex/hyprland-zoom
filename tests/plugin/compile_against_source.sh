#!/usr/bin/env bash
# compile_against_source.sh — compiles the plugin against Hyprland HEADERS taken from a source tree.
# Lets a developer on Hyprland 0.56 check that the plugin still builds for 0.57 (or the other way
# round) without installing that release: the public headers of a release tarball are enough for
# a syntax-only compile (nothing is linked or loaded).
# Usage: tests/plugin/compile_against_source.sh <hyprland-source-dir>
#   <hyprland-source-dir>  an extracted hyprwm/Hyprland tarball (contains src/ and VERSION)
# Needs: g++, pkg-config, tar, the installed hyprland package (for the generated protocol
#        headers) and the hyprutils/aquamarine/hyprlang development files.
# Exit:  0 compiles; 1 compile error; 77 a prerequisite is missing (skipped).
set -euo pipefail

# Repository root, resolved from this script so it works from any directory.
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# Include overlay built below; global so the EXIT trap can still remove it after main returned.
overlay=""

# skip — report a missing prerequisite the conventional way.
# Args:    $1 reason
# Returns: never returns (exit 77); stderr: the reason
# Globals: none
skip() {
  # 77 is the autotools "skipped" status that run.sh understands.
  echo "compile_against_source.sh: SKIP, $1" >&2
  exit 77
}

# stage_headers — copies the headers of the source tree into an include overlay.
# Args:    $1 source dir; $2 destination include dir
# Returns: 0 always; writes <dest>/hyprland/src with the headers and a generated version.h
# Globals: none
stage_headers() {
  local source_dir="$1" destination="$2" name
  mkdir -p "$destination/hyprland/src"
  # Only headers are needed; tar keeps the directory layout of src/.
  (cd "$source_dir/src" && find . \( -name '*.hpp' -o -name '*.h' -o -name '*.h.in' \) -print0 \
    | tar --null -T - -cf -) | tar -C "$destination/hyprland/src" -xf -
  # The generated protocol headers come from the installed hyprland package.
  ln -s /usr/include/hyprland/protocols "$destination/hyprland/protocols"
  # version.h is generated by CMake in a real build; fill the template from the installed libs.
  sed -e "s/@AQUAMARINE_VERSION@/$(pkg-config --modversion aquamarine)/" \
    -e 's/@AQUAMARINE_VERSION_MAJOR@/0/;s/@AQUAMARINE_VERSION_MINOR@/0/' \
    -e 's/@AQUAMARINE_VERSION_PATCH@/0/' \
    -e "s/@HYPRLANG_VERSION@/$(pkg-config --modversion hyprlang)/" \
    -e "s/@HYPRUTILS_VERSION@/$(pkg-config --modversion hyprutils)/" \
    -e "s/@HYPRCURSOR_VERSION@/$(pkg-config --modversion hyprcursor)/" \
    -e "s/@HYPRGRAPHICS_VERSION@/$(pkg-config --modversion hyprgraphics)/" \
    "$destination/hyprland/src/version.h.in" > "$destination/hyprland/src/version.h"
  # The overlay is only a build input; name it in the output so a failure is attributable.
  name="$(tr -d '[:space:]' < "$source_dir/VERSION")"
  echo "compile_against_source.sh: headers of Hyprland $name staged in $destination"
}

# main — stages the headers and compiles both plugin sources syntax-only.
# Args:    $1 Hyprland source dir
# Returns: 0 compiles; 1 compile error; 77 prerequisite missing
# Globals: reads repo_root; writes overlay
main() {
  local source_dir="${1:-}"
  # Every prerequisite is a skip, never a failure: this is an optional developer check.
  [[ -n "$source_dir" && -f "$source_dir/src/plugins/PluginAPI.hpp" ]] \
    || skip "pass an extracted Hyprland source tree (needs src/plugins/PluginAPI.hpp)"
  command -v g++ > /dev/null 2>&1 || skip "g++ not found"
  # The dependencies of Hyprland's public headers must have development files installed.
  pkg-config --exists hyprutils aquamarine hyprlang hyprcursor hyprgraphics \
    || skip "hyprutils/aquamarine/hyprlang/hyprcursor/hyprgraphics development files missing"
  # The generated wayland protocol headers cannot come from a source tarball.
  [[ -d /usr/include/hyprland/protocols ]] || skip "installed hyprland protocol headers missing"
  overlay="$(mktemp -d "${TMPDIR:-/tmp}/hyprzoom-headers.XXXXXX")"
  # The overlay is removed on every way out, also after a compile error.
  trap 'rm -rf "${overlay:-}"' EXIT
  stage_headers "$source_dir" "$overlay"
  # -isystem keeps the foreign headers' own warnings out of the plugin's -Wall -Wextra report.
  # shellcheck disable=SC2046  # pkg-config output is meant to be word-split into flags.
  g++ -fsyntax-only -std=c++2c -Wall -Wextra -Werror -DWLR_USE_UNSTABLE \
    -DHYPRZOOM_VERSION='"0.0.0-compile-check"' \
    -isystem "$overlay/hyprland/protocols" -isystem "$overlay" -isystem "$overlay/hyprland/src" \
    $(pkg-config --cflags pixman-1 libdrm pangocairo libinput libudev wayland-server xkbcommon \
      hyprutils aquamarine hyprlang) \
    "$repo_root/plugin/main.cpp" "$repo_root/plugin/zoom_hook.cpp"
  echo "compile_against_source.sh: OK"
}

main "$@"
